import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const images = Object.fromEntries(
  [
    'today',
    'routines',
    'editor',
    'frequency',
    'calendar',
    'checklist',
    'notes',
    'insights',
  ].map((name) => [
    name,
    `data:image/png;base64,${readFileSync(`docs/screens/${name}.png`).toString('base64')}`,
  ]),
);
const result = buildSync({
  entryPoints: ['src/features/changeRequests/web/index.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  define: { GUIDE_IMAGES: JSON.stringify(images) },
});
const script = result.outputFiles[0].text.replaceAll('</script', '<\\/script');
const html = readFileSync(
  'src/features/changeRequests/web/template.html',
  'utf8',
)
  .replace('/* GUIDE_STYLE */', () =>
    readFileSync('src/features/changeRequests/web/styles.css', 'utf8'),
  )
  .replace('/* GUIDE_SCRIPT */', () => script);
const output = `// Generated by npm run guide:build. Edit catalog/model/web sources instead.\nexport const guideHtml = ${JSON.stringify(html)};\n`;
const paths = [
  ['src/features/changeRequests/generated/guide.ts', output],
  ['docs/change-requests/index.html', html],
];
for (const [path, content] of paths) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content)
      throw new Error(
        `Stale interactive guide: ${path}. Run npm run guide:build.`,
      );
  } else {
    mkdirSync(path.slice(0, path.lastIndexOf('/')), { recursive: true });
    writeFileSync(path, content);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Interactive guide is current.'
    : 'Built bundled and standalone interactive guide.',
);
